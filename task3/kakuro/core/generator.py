"""Random Kakuro generator, used only to get more test boards for the stability experiments.

1. Random layout: interior cells are white, some are blacked out (180° symmetric), then cells
   are blacked out until every run has 2..9 cells.
2. Random filling: a randomized backtracking puts digits 1..9 in the white cells so that every
   run has distinct digits (sums are not involved yet).
3. The clues are the sums of the filled runs.

The result always has at least one solution (the filling). It may have several, which the
experiments report. No learning involved: this is plain random search.
"""

import random

from .board import KakuroBoard


def _runs(white, rows, cols):
    """Yield runs (lists of cells) of the white mask, both directions."""
    for r in range(rows):
        run = []
        for c in range(cols + 1):
            if c < cols and white[r][c]:
                run.append((r, c))
            else:
                if run:
                    yield run
                run = []
    for c in range(cols):
        run = []
        for r in range(rows + 1):
            if r < rows and white[r][c]:
                run.append((r, c))
            else:
                if run:
                    yield run
                run = []


def random_layout(rows, cols, rng, black_ratio=0.18):
    white = [[r > 0 and c > 0 for c in range(cols)] for r in range(rows)]
    for r in range(1, rows):
        for c in range(1, cols):
            if rng.random() < black_ratio:
                white[r][c] = False
                rr, cc = rows - r, cols - c   # symmetric partner inside the interior
                if 1 <= rr < rows and 1 <= cc < cols:
                    white[rr][cc] = False
    changed = True
    while changed:
        changed = False
        for run in list(_runs(white, rows, cols)):
            if len(run) == 1:
                r, c = run[0]
                white[r][c] = False
                changed = True
            elif len(run) > 9:
                r, c = run[len(run) // 2]
                white[r][c] = False
                changed = True
    return white


def random_fill(white, rows, cols, rng, node_limit=200000):
    cells = [(r, c) for r in range(rows) for c in range(cols) if white[r][c]]
    run_of = {}
    for i, run in enumerate(_runs(white, rows, cols)):
        for cell in run:
            run_of.setdefault(cell, []).append(i)
    used = {}  # run index -> digits already used
    values = {}
    nodes = [0]

    def fill(k):
        if k == len(cells):
            return True
        nodes[0] += 1
        if nodes[0] > node_limit:
            return False
        cell = cells[k]
        digits = list(range(1, 10))
        rng.shuffle(digits)
        for d in digits:
            if any(d in used.get(i, ()) for i in run_of[cell]):
                continue
            values[cell] = d
            for i in run_of[cell]:
                used.setdefault(i, set()).add(d)
            if fill(k + 1):
                return True
            for i in run_of[cell]:
                used[i].discard(d)
            del values[cell]
        return False

    return values if fill(0) else None


def to_text(white, values, rows, cols, title):
    lines = ["// " + title]
    for r in range(rows):
        tokens = []
        for c in range(cols):
            if white[r][c]:
                tokens.append(".")
                continue
            across = down = None
            if c + 1 < cols and white[r][c + 1]:
                across, cc = 0, c + 1
                while cc < cols and white[r][cc]:
                    across += values[(r, cc)]
                    cc += 1
            if r + 1 < rows and white[r + 1][c]:
                down, rr = 0, r + 1
                while rr < rows and white[rr][c]:
                    down += values[(rr, c)]
                    rr += 1
            if across is None and down is None:
                tokens.append("#")
            else:
                tokens.append("{}\\{}".format(down if down is not None else "", across if across is not None else ""))
        lines.append(" ".join(t.ljust(6) for t in tokens).rstrip())
    return "\n".join(lines) + "\n"


def generate(rows, cols, seed, black_ratio=0.18):
    """Return (puzzle text, the filling used to build it)."""
    rng = random.Random(seed)
    while True:
        white = random_layout(rows, cols, rng, black_ratio)
        if sum(map(sum, white)) < (rows - 1) * (cols - 1) // 2:
            continue
        values = random_fill(white, rows, cols, rng)
        if values is None:
            continue
        title = "Random {}x{} board, seed {} (generated by kakuro/core/generator.py)".format(rows, cols, seed)
        text = to_text(white, values, rows, cols, title)
        KakuroBoard.from_text(text)  # sanity check: must parse
        return text, values
