"""Agent interface shared by our agents and by agents imported from other groups."""

from abc import ABC, abstractmethod


class SearchStats:
    """Per-move statistics reported by search agents (used by the GUI and the experiments)."""

    def __init__(self):
        self.nodes = 0          # game-tree nodes visited (MAX + MIN nodes)
        self.states = 0         # game states generated by the transition function
        self.evaluations = 0    # leaves scored by the utility / evaluation function
        self.cutoffs = 0        # alpha-beta prunings
        self.depth = 0          # deepest fully completed search depth (in game cycles)
        self.max_ply = 0        # deepest ply reached (1 cycle = 2 plies)
        self.peak_memory = 0    # most nodes held at once: nodes on the current path + their untried
                                # successors (depth-first search: O(b*m))
        self.tt_entries = 0     # transposition-table entries stored at the end of the search
        self.tt_hits = 0        # transposition-table lookups that could be used
        self.time = 0.0         # seconds
        self.value = None       # minimax value of the chosen move
        self.timed_out = False

    def as_dict(self):
        return dict(self.__dict__)


class BaseAgent(ABC):
    """Every agent controls one tank.

    Subclasses implement `choose_action(state)` which receives a copy of the current GameState and
    returns an `Action` (or its name as a string). `self.player` is 0 (P1) or 1 (P2).
    """

    name = "Agent"
    description = ""

    def __init__(self, player, **kwargs):
        self.player = player
        self.opponent = 1 - player
        self.last_stats = SearchStats()

    def reset(self):
        """Called before a new game."""
        self.last_stats = SearchStats()

    @abstractmethod
    def choose_action(self, state):
        raise NotImplementedError

    def __repr__(self):
        return "%s(player=%d)" % (self.name, self.player)
